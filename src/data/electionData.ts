export function formatSignedMargin(val: number, showUnit = false): string {
  const abs = Math.abs(val).toFixed(1);
  const unit = showUnit ? ' pts' : '';
  if (val > 0.04) return `+${abs}${unit}`;
  if (val < -0.04) return `-${abs}${unit}`;
  return `0.0${unit}`;
}

export function formatPartyMargin(val: number): string {
  const abs = Math.abs(val).toFixed(1);
  if (val > 0.04) return `D+${abs}`;
  if (val < -0.04) return `R+${abs}`;
  return 'EVEN';
}

